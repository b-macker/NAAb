#!/usr/bin/env bash
# A33(b): the variables that hold the engine's own keys are withheld from the
# program.
#
# telemetry.tamper_evidence.hmac_key_env, audit.tamper_evidence.hmac_key_env and
# audit.provenance.signing_key_env name the variable the engine reads a key
# from: the telemetry chain's HMAC key, the audit chain's, the attestation
# signing key's path. The program could read each with env.get and seal lines
# it forges (observed on c1312132: env.get printed the value, exit 0). Each
# name now joins env_vars.blocked_read for the run, grow-only, as a guidance
# source's auth_env does (addGovernanceProtectedPaths), so env.get refuses it at
# HARD and no child the program starts receives it.
#
# Every name and value here is generated by this suite; no real key is read.
#
#   KW-00  CONTROL: an unrelated variable is read (the program runs)
#   KW-01  telemetry.tamper_evidence.hmac_key_env: env.get refused, exit 3 (red on c1312132)
#   KW-02  audit.tamper_evidence.hmac_key_env: the same                  (red on c1312132)
#   KW-03  audit.provenance.signing_key_env: the same                    (red on c1312132)
#   KW-04  a child process does not receive the telemetry key variable  (red on c1312132)
#   KW-04c CONTROL: the same child receives the unrelated variable
#
# Kill table (mutants, run by hand, revert-checked 2026-11-20):
#   W1 key_env_names not added to protected_env_names_    -> KW-01..KW-04
#   W2 the telemetry name not recorded at parse           -> KW-01, KW-04
#   W3 the audit name not recorded                        -> KW-02
#   W4 the signing name not recorded                      -> KW-03
set -u
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
NAAB="${NAAB:-$REPO/build/naab-lang}"
W="$(mktemp -d)"
source "$REPO/tests/helpers/trust_setup.sh"
source "$REPO/tests/helpers/native_path.sh"   # KW-04 hands the binary a program path
setup_isolated_trust
trap 'teardown_isolated_trust; rm -rf "$W"' EXIT

PASS=0; FAIL=0; SKIP=0
ok()   { echo "  PASS [$1] $2"; PASS=$((PASS+1)); }
bad()  { echo "  FAIL [$1] $2"; [ -n "${3:-}" ] && printf '%s\n' "$3" | head -12 | sed 's/^/      | /'; FAIL=$((FAIL+1)); }
skip() { echo "  SKIP [$1] UNMEASURABLE: $2"; SKIP=$((SKIP+1)); }
[ -x "$NAAB" ] || { echo "not built: $NAAB"; exit 1; }

TAG="k33$$${RANDOM}"
NT="NAAB_${TAG}_T"; NA="NAAB_${TAG}_A"; NS="NAAB_${TAG}_S"; NF="NAAB_${TAG}_FREE"
VT="vt-${TAG}"; VA="va-${TAG}"; VS="$W/vs-${TAG}.pem"; VF="vf-${TAG}"
export "$NT=$VT" "$NA=$VA" "$NS=$VS" "$NF=$VF"

cat > "$W/govern.json" <<EOF
{"version": "5.0", "mode": "enforce", "security": {"sandbox_level": "elevated"},
 "telemetry": {"tamper_evidence": {"enabled": true, "hmac_key_env": "$NT"}},
 "audit": {"tamper_evidence": {"enabled": true, "hmac_key_env": "$NA"},
           "provenance": {"signing_key_env": "$NS"}}}
EOF
# go ID NAAB-CALL -> RC, OUT
go() {
    printf 'use env\nuse process\nmain {\n    let v = %s\n    print("GOT=" + string(v))\n}\n' "$2" > "$W/$1.naab"
    OUT="$(cd "$W" && timeout 60 "$NAAB" run "$1.naab" 2>&1)"; RC=$?
}

go kw0 "env.get(\"$NF\")"
if [ "$RC" -eq 0 ] && grep -q "GOT=$VF" <<<"$OUT"; then ok KW-00 "an unrelated variable is read (exit 0)"; live=1
else bad KW-00 "the unrelated variable was not read (rc=$RC)" "$OUT"; live=0; fi

for row in "KW-01|$NT|$VT|telemetry.tamper_evidence.hmac_key_env" \
           "KW-02|$NA|$VA|audit.tamper_evidence.hmac_key_env" \
           "KW-03|$NS|$VS|audit.provenance.signing_key_env"; do
    IFS='|' read -r id name val key <<<"$row"
    go "g$id" "env.get(\"$name\")"
    if [ "$live" -ne 1 ]; then skip "$id" "KW-00 did not run"
    elif [ "$RC" -eq 3 ] && ! grep -qF "$val" <<<"$OUT" && grep -q 'blocked_read' <<<"$OUT"; then
        ok "$id" "the variable $key names is refused at HARD (exit 3)"
    else bad "$id" "the $key variable was readable (rc=$RC)" "$OUT"; fi
done

PR="$(command -v printenv || true)"
# The program is run by naab-lang, a native binary under MSYS2: hand it the
# path in ITS vocabulary (native_path.sh), with the .exe the file has there.
[ -n "$PR" ] && [ -f "$PR.exe" ] && PR="$PR.exe"
[ -n "$PR" ] && PR="$(native_path "$PR")"
if [ -z "$PR" ]; then skip KW-04 "no printenv here"; skip KW-04c "no printenv here"
else
    go kw4c "process.run(\"$PR\", [\"$NF\"])"
    if grep -q "$VF" <<<"$OUT"; then ok KW-04c "a child receives the unrelated variable"; c=1
    elif grep -qE 'CreateProcess failed|No such file|cannot execute' <<<"$OUT"; then
        skip KW-04c "the child could not be started here (rc=$RC)"; c=0
    else bad KW-04c "the child did not receive the unrelated variable (rc=$RC)" "$OUT"; c=0; fi
    go kw4 "process.run(\"$PR\", [\"$NT\"])"
    if [ "$c" -ne 1 ]; then skip KW-04 "KW-04c did not run"
    elif ! grep -qF "$VT" <<<"$OUT"; then ok KW-04 "a child does not receive the telemetry key variable"
    else bad KW-04 "the child printed the telemetry key" "$OUT"; fi
fi

echo
echo "Results: $PASS passed, $FAIL failed, $SKIP unmeasurable"
[ "$FAIL" -eq 0 ]
